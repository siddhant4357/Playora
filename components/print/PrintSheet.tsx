import type { ReactNode } from "react";
import Link from "next/link";
import "./print.css";
import { PrintButton } from "./PrintButton";

interface ClubLike {
  name: string;
  tagline?: string | null;
  address?: string | null;
  phone?: string | null;
  email?: string | null;
}

interface Props {
  club: ClubLike;
  docType: string;
  docNo: string;
  date: string;
  meta?: [string, string][];
  to: { name: string; lines: string[] };
  children: ReactNode;
  footer?: ReactNode;
}

/**
 * A4-friendly document shell for quotes, invoices and payslips. Print to PDF
 * from the browser — one layout, no PDF library.
 */
export function PrintSheet({ club, docType, docNo, date, meta = [], to, children, footer }: Props) {
  return (
    <main className="ps">
      <header className="ps-head">
        <div>
          <p className="ps-brand">{club.name}</p>
          {club.tagline && <p className="ps-muted">{club.tagline}</p>}
          <p className="ps-muted">{[club.address, club.phone, club.email].filter(Boolean).join(" · ")}</p>
        </div>
        <div className="ps-doc">
          <p className="ps-doctype">{docType}</p>
          <p>
            <b>{docNo}</b>
          </p>
          <p className="ps-muted">{date}</p>
          {meta.map(([k, v]) => (
            <p key={k} className="ps-muted">
              {k}: {v}
            </p>
          ))}
        </div>
      </header>
      <section className="ps-to">
        <p className="ps-label">To</p>
        <p>
          <b>{to.name}</b>
        </p>
        {to.lines.map((l) => (
          <p key={l} className="ps-muted">
            {l}
          </p>
        ))}
      </section>
      {children}
      <footer className="ps-foot">{footer ?? <p className="ps-muted">Generated by Playora for {club.name}. Thank you for playing with us.</p>}</footer>
    </main>
  );
}

export function PrintToolbar({ backHref }: { backHref: string }) {
  return (
    <div className="ps-toolbar">
      <Link href={backHref}>← Back</Link>
      <PrintButton />
    </div>
  );
}
